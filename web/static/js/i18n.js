/**
 * 模块名称：界面多语言（i18n.js）
 * 功能描述：面板的中英文案表与取词入口 T()；setLang() 把语言应用到 data-i18n 系列属性、
 *           .cn-text / .en-text 显隐与 documentElement.lang；toggleLang() / initLang() 与后端同步，语言存服务端。
 * 职责边界：负责：key 到文案的查表、静态文案替换，以及动态内容重绘入口的登记与回放；
 *           不负责：占位符填充与动态内容拼装（由 common.js 的 fillTemplate 和各页面脚本负责）。
 * 关键依赖：jQuery 的 $（setLang 改写 DOM 与显隐切换）；common.js 的 appendToken、jqErrorText；
 *           app.js 的 toast、svcBtns；本文件在 index.html 中先于 common.js 加载，跨文件调用只允许发生在运行期。
 * 已知限制：
 *           1. 中英两包的键集合必须完全一致；少一个 key 不报错，只会让该位置在另一种语言下混进中文，增删 key 时两包要一起改。
 *           2. T() 缺 key 时原样返回 key 名，写 T().xxx || “默认值” 也没有兜底；两级枚举的第二级要写 T().xxx[k] || k。
 *           3. data-i18n 用 $(el).text(v) 写入会清空子节点，不能挂在带子元素的标签上；-title / -placeholder 用 attr() 写入。
 *           4. data-i18n 管着的元素不能再被脚本用 .text() / .html() 写，否则切语言时真实状态会被固定文案盖掉。
 *           5. onLangRender 的实参必须是具名函数本身：就地写闭包每次求值都是新对象，去重不命中，登记表会随回放无界增长。
 *           6. 占位符统一用 {}，由调用方经 common.js 的 fillTemplate 按序填充；{name} 式具名占位不被识别。
 *           7. en 包的 unit_* 量词为空串是有意为之：英文不加后缀，由 main.css 的 .fg-unit:empty 收起，不要补值。
 */

var lang = 'cn';

var _tProxy = new Proxy({}, {
  get: function (_, key) {
    var cur = translations[lang] || translations.cn || {};
    if (cur[key] !== undefined) return cur[key];
    var cn = translations.cn || {};
    return cn[key] !== undefined ? cn[key] : key;
  }
});

function T() { return _tProxy; }

function _resolveText(key) {
  var cur = translations[lang] || {};
  if (cur[key] !== undefined) return cur[key];
  var cn = translations.cn || {};
  return cn[key];
}

var _langRenderers = [];

function onLangRender(fn) {
  if (_langRenderers.indexOf(fn) === -1) _langRenderers.push(fn);
}

function _replayLangRenderers() {
  _langRenderers.slice().forEach(function (fn) {
    try {
      fn();
    } catch (e) {
      if (typeof console !== 'undefined' && console.warn) {
        console.warn('[i18n] 切换语言时重绘失败:', fn && fn.name, e);
      }
    }
  });
}

function setLang(ln) {
  lang = ln;

  $('[data-i18n]').each(function () {
    var v = _resolveText($(this).data('i18n'));
    if (v !== undefined) $(this).text(v);
  });
  $('[data-i18n-title]').each(function () {
    var v = _resolveText($(this).data('i18n-title'));
    if (v !== undefined) $(this).attr('title', v);
  });

  $('[data-i18n-placeholder]').each(function () {
    var v = _resolveText($(this).data('i18n-placeholder'));
    if (v !== undefined) $(this).attr('placeholder', v);
  });

  $('.cn-text').toggle(ln === 'cn');
  $('.en-text').toggle(ln === 'en');
  $('#lang-btn i').attr('class', 'fa fa-globe');
  document.documentElement.lang = (ln === 'cn') ? 'zh-CN' : 'en';

  _replayLangRenderers();
}

function toggleLang() {
  var nl = lang === 'cn' ? 'en' : 'cn';
  $.ajax({
    url: appendToken('/api/language'),
    method: 'POST',
    contentType: 'application/json',
    data: JSON.stringify({ language: nl }),
    success: function (r) {
      if (r.status === 'success') setLang(nl);
      else toast(r.message || T().operation_failed_bare, 'error');
    },
    error: function (x) {
      toast(T().request_failed + T().sep_colon + jqErrorText(x, T().network_error), 'error');
    }
  });
}

function initLang() {
  $.get(appendToken('/api/status'), function (d) {
    setLang(d.language || 'cn');
    svcBtns(d.service_status);
  });
}

